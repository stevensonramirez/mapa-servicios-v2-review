const LANG_KEY = "mapa-servicios-v2:lang";

const readLang = (): Lang => {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v === "es" || v === "en" || v === "fr" || v === "de") return v;
  } catch {
    /* sandbox sin localStorage */
  }
  return "es";
};

type LanguageContextValue = { lang: Lang; setLang: (l: Lang) => void };

const LanguageContext = createContext<LanguageContextValue>({ lang: "es", setLang: () => undefined });

export const LanguageProvider = ({ children }: { children: React.ReactNode }) => {
  const [lang, setLangState] = useState<Lang>(readLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_KEY, l);
    } catch {
      /* sandbox sin localStorage */
    }
  }, []);
  return <LanguageContext.Provider value={{ lang, setLang }}>{children}</LanguageContext.Provider>;
};

export const useLang = () => useContext(LanguageContext);

// Función de traducción con interpolación de variables ({nombre} → vars.nombre).
export const useT = () => {
  const { lang } = useLang();
  const t = useCallback(
    (key: string, vars?: Record<string, string | number>): string => {
      const dict = TRANSLATIONS[lang];
      const fallback = TRANSLATIONS.es;
      let str = dict[key] ?? fallback[key] ?? key;
      if (vars) {
        Object.entries(vars).forEach(([k, v]) => {
          // Reemplazo por FUNCIÓN: si el valor viene como string directo, los
          // patrones $$ / $& / $' de replace() se interpretan — un mapa llamado
          // "Presupuesto $$ 2026" salía mutilado en los mensajes.
          str = str.replace(new RegExp(`\\{${k}\\}`, "g"), () => String(v));
        });
      }
      return str;
    },
    [lang],
  );
  return t;
};
